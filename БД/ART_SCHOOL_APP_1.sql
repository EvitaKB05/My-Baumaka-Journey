/* --------------------------------------------------------- */

/* 1 - housings */
CREATE TABLE IF NOT EXISTS housings (
id_housing INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
title VARCHAR,
address VARCHAR
);
SELECT * FROM housings;

/* 2 - faculties */
CREATE TABLE IF NOT EXISTS faculties (
id_faculty INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
title VARCHAR,
id_housing INT,
FOREIGN KEY (id_housing) REFERENCES housings (id_housing)
);
SELECT * FROM faculties;

/* 3 - teachers */
CREATE TABLE IF NOT EXISTS teachers (
id_teacher INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
fio VARCHAR,
contacts VARCHAR,
post VARCHAR,
id_faculty INT,
FOREIGN KEY (id_faculty) REFERENCES faculties (id_faculty)
);
SELECT * FROM teachers;

/* 4 - students */
CREATE TABLE IF NOT EXISTS students (
id_student INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
fio VARCHAR,
contacts VARCHAR,
id_faculty INT,
FOREIGN KEY (id_faculty) REFERENCES faculties (id_faculty)
);
SELECT * FROM students;

/* 5 subjects */
CREATE TABLE IF NOT EXISTS subjects (
id_subject INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
title VARCHAR,
learning_hours NUMERIC,
id_faculty INT,
FOREIGN KEY (id_faculty) REFERENCES faculties (id_faculty)
);
SELECT * FROM subjects;

/* 6 - marks */
CREATE TABLE IF NOT EXISTS marks (
id_mark INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
mark_type VARCHAR,
id_subject INT,
id_student INT,
mark NUMERIC,
id_teacher INT,
date_m DATE,
id_schedule INT,
FOREIGN KEY (id_subject) REFERENCES subjects (id_subject),
FOREIGN KEY (id_student) REFERENCES students (id_student),
FOREIGN KEY (id_teacher) REFERENCES teachers (id_teacher),
FOREIGN KEY (id_schedule) REFERENCES schedules(id_schedule)
);
SELECT * FROM marks;

/*7 - schedules */
CREATE TABLE IF NOT EXISTS schedules (
    id_schedule INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_faculty INT,
    id_subject INT,
    week_day VARCHAR(20),
    time TIME,
    lesson_type VARCHAR(50),
    id_teacher INT,
    FOREIGN KEY (id_faculty) REFERENCES faculties (id_faculty),
    FOREIGN KEY (id_subject) REFERENCES subjects (id_subject),
    FOREIGN KEY (id_teacher) REFERENCES teachers (id_teacher)
);
SELECT * FROM schedules;

