/* 8 - sub_teachers */
CREATE TABLE IF NOT EXISTS sub_teachers (
id_sub_teacher INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
id_subject INT,
id_teacher INT,
FOREIGN KEY (id_subject) REFERENCES subjects (id_subject),
FOREIGN KEY (id_teacher) REFERENCES teachers (id_teacher)
);
SELECT * FROM sub_teachers;

/* 9 - sub_students */
CREATE TABLE IF NOT EXISTS sub_students (
id_sub_student INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
id_subject INT,
id_student INT,
FOREIGN KEY (id_subject) REFERENCES subjects (id_subject),
FOREIGN KEY (id_student) REFERENCES students (id_student)
);
SELECT * FROM sub_students;

