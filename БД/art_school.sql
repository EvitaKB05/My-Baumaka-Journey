-- 2. Create a simple view and query data
CREATE VIEW v_teacher_subjects AS
SELECT t.fio, s.title
FROM teachers t
JOIN sub_teachers st ON t.id_teacher = st.id_teacher
JOIN subjects s ON st.id_subject = s.id_subject;

SELECT * FROM v_teacher_subjects;

