-- 7. Create a view with WITH CHECK OPTION
CREATE OR REPLACE VIEW v_high_marks AS
SELECT id_mark, mark_type, id_subject, id_student, mark
FROM marks
WHERE mark >= 4
WITH CHECK OPTION;


SELECT * FROM v_high_marks;

-- Attempt to insert data that violates the condition (should fail)
